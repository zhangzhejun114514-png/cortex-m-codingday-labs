; =====================================================================
; Block 1.5 Coding Day  Task 2 : Experimenting Load/Store (2)
; 使用前请在 Keil 调试器里先把内存写好 (Memory 窗口):
;   0x20008000 = EE   0x20008001 = 8C   0x20008002 = 90   0x20008003 = A7
;   0x20008004 = A0   0x20008005 = A0   0x20008006 = A0   0x20008007 = A0
; 即 32 位字 mem[0x20008000] = 0xA7908CEE
; =====================================================================
        AREA    |.text|, CODE, READONLY

__main  PROC
        ; ---------------- (A) LDRH ----------------
        LDR     r0, =0x20008000
        LDRH    r1, [r0]            ; r1 = 0x00008CEE

        ; ---------------- (B) LDRSB ---------------
        ; 幻灯片写作 LDSB, 正确助记符是 LDRSB
        LDR     r0, =0x20008000
        LDRSB   r1, [r0]            ; r1 = 0xFFFFFFEE  ( = -18 )

        ; ---------------- (C) 后索引 STR ----------
        ; STR r1, [r0], #4 : 先按 r0 存, 再 r0 = r0 + 4
        LDR     r0, =0x20008000
        LDR     r1, =0x07654321
        STR     r1, [r0], #4        ; 存入 0x20008000..03 = 21 43 65 07 ; r0 = 0x20008004

        ; ---------------- (D) 偏移 STR ------------
        ; STR r1, [r0, #4] : 存到 0x20008004, r0 不变
        LDR     r0, =0x20008000
        LDR     r1, =0x76543210
        STR     r1, [r0, #4]        ; 存入 0x20008004..07 = 10 32 54 76 ; r0 = 0x20008000

        ; ---------------- (E) 前索引 STR ----------
        ; STR r1, [r0, #4]! : 先 r0 = r0 + 4, 再按 r0 存
        LDR     r0, =0x20008000
        LDR     r1, =0x76543210
        STR     r1, [r0, #4]!       ; 存入 0x20008004..07 = 10 32 54 76 ; r0 = 0x20008004
loop    B       loop
        ENDP

        ALIGN

        END