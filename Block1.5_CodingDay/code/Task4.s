; =====================================================================
; Block 1.5 Coding Day  Task 4 : Experimenting Addressing Modes (2)
; 初始 : r0 = 0x20000000 , r1 = 0x12345678
; 目标 : 追踪多次 STR 后 r0 的最终值, 并记录写了哪些内存
;   STR r1, [r0], #4     : 存到 r0, 然后 r0 += 4   -> r0 = 0x20000004
;   STR r1, [r0, #8]!    : r0 += 8, 再存到 r0     -> r0 = 0x2000000C
;   STR r1, [r0]         : 存到 r0                 -> r0 = 0x2000000C
; 结论 : 最终 r0 = 0x2000000C
; =====================================================================
        AREA    |.text|, CODE, READONLY

__main  PROC
        LDR     r0, =0x20000000
        LDR     r1, =0x12345678
        STR     r1, [r0], #4        ; 0x20000000..03 = 78 56 34 12 ; r0 = 0x20000004
        STR     r1, [r0, #8]!       ; 0x2000000C..0F = 78 56 34 12 ; r0 = 0x2000000C
        STR     r1, [r0]            ; 0x2000000C..0F = 78 56 34 12 ; r0 = 0x2000000C
loop    B       loop
        ENDP

        ALIGN

        END